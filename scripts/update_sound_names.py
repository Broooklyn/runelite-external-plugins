#!/usr/bin/env python3
"""Regenerates the debug sound name maps from RuneLite's gameval ids.

    python3 scripts/update_sound_names.py

Downloads AmbientSoundID.java and SoundEffectID.java from the RuneLite master branch and rewrites
AmbientSoundNames.java and SoundNames.java in src/test/java/com/brooklyn/annoyancemute/debug/.
The files are only written when their content changes. Pass --check to only report whether they are up to date
(exit code 1 if not), and --ref <branch|tag|sha> to read from something other than master.
"""
import argparse
import re
import sys
import urllib.request
from pathlib import Path

RAW_URL = "https://raw.githubusercontent.com/runelite/runelite/{ref}/runelite-api/src/main/java/net/runelite/api/gameval/{name}.java"
DEBUG_DIR = Path(__file__).resolve().parent.parent / "src/test/java/com/brooklyn/annoyancemute/debug"
CONSTANT = re.compile(r"public static final int ([A-Za-z0-9_]+) = (-?\d+);")
# keeps every init method well under the JVM's 64KB method size limit
CHUNK_SIZE = 1500


def fetch(name, ref):
    with urllib.request.urlopen(RAW_URL.format(ref=ref, name=name), timeout=60) as response:
        return response.read().decode("utf-8")


def parse(source):
    """id -> lowercase name. When several constants share an id the first one wins."""
    names = {}
    for constant, value in CONSTANT.findall(source):
        names.setdefault(int(value), constant.lower())
    return dict(sorted(names.items()))


def ambient_sound_names(names):
    lines = [
        "package com.brooklyn.annoyancemute.debug;",
        "",
        "import java.util.HashMap;",
        "import java.util.Map;",
        "import javax.annotation.Nullable;",
        "",
        "/**",
        " * Names of the location based ambient sounds (AmbientSoundID), for display in the debug overlay.",
        " * Generated by scripts/update_sound_names.py, do not edit by hand.",
        " */",
        "class AmbientSoundNames",
        "{",
        "\tprivate static final Map<Integer, String> NAMES = new HashMap<>();",
        "",
        "\tstatic",
        "\t{",
    ]
    lines += [f'\t\tNAMES.put({i}, "{n}");' for i, n in names.items()]
    lines += [
        "\t}",
        "",
        "\tprivate AmbientSoundNames()",
        "\t{",
        "\t}",
        "",
        "\t@Nullable",
        "\tstatic String get(int ambientSoundId)",
        "\t{",
        "\t\treturn NAMES.get(ambientSoundId);",
        "\t}",
        "}",
    ]
    return "\n".join(lines) + "\n"


def sound_names(names):
    entries = list(names.items())
    chunks = [entries[i:i + CHUNK_SIZE] for i in range(0, len(entries), CHUNK_SIZE)]
    lines = [
        "package com.brooklyn.annoyancemute.debug;",
        "",
        "import java.util.HashMap;",
        "import java.util.Map;",
        "import javax.annotation.Nullable;",
        "",
        "/**",
        " * Names of the sound effects (SoundEffectID), for display in the debug overlay.",
        " * Split into several methods because a single one holding every entry is over the JVM method size limit.",
        " * Generated by scripts/update_sound_names.py, do not edit by hand.",
        " */",
        "class SoundNames",
        "{",
        f"\tprivate static final Map<Integer, String> NAMES = new HashMap<>({max(16, len(entries) * 4 // 3 + 1)});",
        "",
        "\tstatic",
        "\t{",
    ]
    lines += [f"\t\tinit{n + 1}();" for n in range(len(chunks))]
    lines += [
        "\t}",
        "",
        "\tprivate SoundNames()",
        "\t{",
        "\t}",
        "",
        "\t@Nullable",
        "\tstatic String get(int soundId)",
        "\t{",
        "\t\treturn NAMES.get(soundId);",
        "\t}",
        "",
    ]
    for n, chunk in enumerate(chunks):
        lines += [f"\tprivate static void init{n + 1}()", "\t{"]
        lines += [f'\t\tNAMES.put({i}, "{name}");' for i, name in chunk]
        lines += ["\t}", ""]
    lines[-1] = "}"
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="don't write, exit 1 if the files are out of date")
    parser.add_argument("--ref", default="master", help="RuneLite branch, tag or commit to read (default: master)")
    args = parser.parse_args()

    targets = [
        ("AmbientSoundID", "AmbientSoundNames.java", ambient_sound_names, 1),
        ("SoundEffectID", "SoundNames.java", sound_names, 1000),
    ]

    stale = False
    for source_name, file_name, render, minimum in targets:
        names = parse(fetch(source_name, args.ref))
        if len(names) < minimum:
            # the source format probably changed; don't wipe the maps
            sys.exit(f"{source_name}: only found {len(names)} ids, expected at least {minimum}. Has the format changed?")

        path = DEBUG_DIR / file_name
        content = render(names)
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            print(f"{file_name}: up to date ({len(names)} names)")
            continue

        stale = True
        if args.check:
            print(f"{file_name}: out of date")
        else:
            path.write_text(content, encoding="utf-8", newline="\n")
            print(f"{file_name}: updated ({len(names)} names)")

    if args.check and stale:
        sys.exit(1)


if __name__ == "__main__":
    main()
